/**
 * Supabase Storage Gallery Utility
 *
 * Provides authenticated, RLS-governed uploads to private storage buckets:
 * - `roa-gallery`: Original community photographs (max 20 MB)
 * - `roa-thumbnails`: Generated WebP thumbnails (max 10 MB)
 *
 * Security & Defensive Hardening:
 * - Independent validation of all upload inputs (sizes, MIME types, blob types)
 * - Extension and content-type derived strictly from canonical validated MIME type
 * - Filename extensions cannot override or contradict the validated MIME type
 * - Strict regex recognition of user-scoped Supabase Storage paths: `<user-uuid>/<filename>.<ext>`
 * - Client-side authenticated Supabase client only (no service-role key in browser code)
 * - Both buckets are private (never public, never use getPublicUrl)
 * - Explicit upsert: false
 * - Reliable rollback of original image if thumbnail upload fails
 * - Signed URLs generated with temporary 1-hour expiry on demand
 * - Never returns a raw private Storage path when signing fails
 * - Never persists signed URLs in localStorage or the database
 * - Local static paths (/...) and external HTTP(S) URLs are preserved untouched
 */

import { supabase, isSupabaseConfigured } from '../lib/supabase';

export const GALLERY_ORIGINAL_BUCKET = 'roa-gallery';
export const GALLERY_THUMBNAIL_BUCKET = 'roa-thumbnails';
export const DEFAULT_SIGNED_URL_EXPIRY_SECONDS = 3600; // 1 hour

export const MAX_ORIGINAL_FILE_SIZE_BYTES = 20 * 1024 * 1024; // 20 MB
export const MAX_THUMBNAIL_FILE_SIZE_BYTES = 10 * 1024 * 1024; // 10 MB

export const ALLOWED_CANONICAL_MIME_TYPES = [
  'image/jpeg',
  'image/png',
  'image/webp'
] as const;

export type AllowedCanonicalMimeType = typeof ALLOWED_CANONICAL_MIME_TYPES[number];

export interface UploadedGalleryPaths {
  imagePath: string;
  thumbnailPath: string;
}

export interface StorageCleanupResult {
  ok: boolean;
  errors: string[];
}

/**
 * Regular expression strictly matching the Supabase Storage object path format generated by this project:
 * - First segment: Authenticated user UUID (8-4-4-4-12 hex digits)
 * - Slash separator: `/`
 * - Second segment: Timestamp_UUID/randomID filename with supported image extension (.jpg, .jpeg, .png, .webp)
 */
export const STORAGE_PATH_PATTERN =
  /^[0-9a-fA-F]{8}-[0-9a-fA-F]{4}-[0-9a-fA-F]{4}-[0-9a-fA-F]{4}-[0-9a-fA-F]{12}\/[a-zA-Z0-9_-]+\.(jpe?g|png|webp)$/i;

/**
 * Checks whether an image path matches the specific private Supabase Storage path format
 * produced by this project.
 *
 * Classification:
 * - Leading-slash paths (`/images/...`) -> false (preserved as local static assets)
 * - HTTP/HTTPS URLs (`http://...`, `https://...`) -> false (preserved as external URLs)
 * - Data URLs (`data:...`) -> false (preserved as embedded data)
 * - Blob URLs (`blob:...`) -> false (preserved as local object URLs)
 * - User-scoped Supabase Storage path (`<user-uuid>/<filename>.<ext>`) -> true
 * - Any other string (arbitrary text, directory traversal, malformed) -> false
 */
export function isStoragePath(path: string | null | undefined): boolean {
  if (!path || typeof path !== 'string') return false;
  const trimmed = path.trim();
  if (trimmed === '') return false;

  // Preserve local static assets starting with /
  if (trimmed.startsWith('/')) return false;

  // Preserve external or embedded URLs
  if (/^(https?:|data:|blob:)/i.test(trimmed)) return false;

  // Strictly recognize only the actual Supabase Storage path format generated by this project
  return STORAGE_PATH_PATTERN.test(trimmed);
}

/**
 * Derives canonical file extension and content type directly from the validated MIME type.
 * Ensures the filename extension cannot override or contradict the validated MIME type.
 */
export function resolveFileExtension(
  validatedMimeType: string,
  filename?: string
): { ext: 'jpg' | 'png' | 'webp'; contentType: AllowedCanonicalMimeType } {
  if (!validatedMimeType || typeof validatedMimeType !== 'string') {
    throw new Error('A canonical validated MIME type is required to resolve file extension.');
  }

  const normalizedMime = validatedMimeType.trim().toLowerCase();

  let canonical: { ext: 'jpg' | 'png' | 'webp'; contentType: AllowedCanonicalMimeType };

  switch (normalizedMime) {
    case 'image/jpeg':
    case 'image/pjpeg':
      canonical = { ext: 'jpg', contentType: 'image/jpeg' };
      break;
    case 'image/png':
      canonical = { ext: 'png', contentType: 'image/png' };
      break;
    case 'image/webp':
      canonical = { ext: 'webp', contentType: 'image/webp' };
      break;
    default:
      throw new Error(
        `Unsupported MIME type '${validatedMimeType}'. Only image/jpeg, image/png, and image/webp are accepted.`
      );
  }

  // If a filename is provided, verify its extension does not contradict the validated MIME type
  if (filename && typeof filename === 'string') {
    const parts = filename.split('.');
    if (parts.length >= 2) {
      const fileExt = parts.pop()?.trim().toLowerCase() || '';
      const allowedExts: Record<'jpg' | 'png' | 'webp', string[]> = {
        jpg: ['jpg', 'jpeg'],
        png: ['png'],
        webp: ['webp']
      };

      if (!allowedExts[canonical.ext].includes(fileExt)) {
        throw new Error(
          `Filename extension '.${fileExt}' contradicts validated MIME type '${canonical.contentType}'.`
        );
      }
    }
  }

  return canonical;
}

/**
 * Generates a collision-resistant unique identifier.
 */
function generateUniqueId(): string {
  if (typeof crypto !== 'undefined' && typeof crypto.randomUUID === 'function') {
    return crypto.randomUUID();
  }
  return `${Date.now()}_${Math.random().toString(36).substring(2, 12)}`;
}

/**
 * Uploads original photo and generated WebP thumbnail to their respective private buckets.
 *
 * Defensive validations:
 * - Validates original file presence, non-zero size, and <= 20 MB limit.
 * - Requires and validates canonical MIME type (image/jpeg, image/png, image/webp).
 * - Validates thumbnail blob presence, non-zero size, type === 'image/webp', and <= 10 MB limit.
 * - Authenticates staff session.
 * - Uses upsert: false.
 * - Rolls back original image if thumbnail upload fails.
 */
export async function uploadGalleryImages(
  originalFile: File,
  thumbnailBlob: Blob,
  validatedMimeType: string
): Promise<UploadedGalleryPaths> {
  // 1. Independent validation of originalFile
  if (!originalFile) {
    throw new Error('Original image file is required.');
  }
  if (originalFile.size <= 0) {
    throw new Error('Original image file is empty (0 bytes).');
  }
  if (originalFile.size > MAX_ORIGINAL_FILE_SIZE_BYTES) {
    const sizeInMB = (originalFile.size / (1024 * 1024)).toFixed(1);
    throw new Error(`Original image file (${sizeInMB} MB) exceeds the maximum allowed limit of 20 MB.`);
  }

  // 2. Independent validation of canonical validated MIME type
  if (!validatedMimeType || typeof validatedMimeType !== 'string') {
    throw new Error('A canonical validated MIME type is required.');
  }
  const normalizedMime = validatedMimeType.trim().toLowerCase();
  if (!ALLOWED_CANONICAL_MIME_TYPES.includes(normalizedMime as AllowedCanonicalMimeType)) {
    throw new Error(
      `Unsupported MIME type '${validatedMimeType}'. Only image/jpeg, image/png, and image/webp are accepted.`
    );
  }

  // 3. Independent validation of thumbnailBlob
  if (!thumbnailBlob) {
    throw new Error('Thumbnail blob is required.');
  }
  if (thumbnailBlob.size <= 0) {
    throw new Error('Thumbnail blob is empty (0 bytes).');
  }
  if (thumbnailBlob.type !== 'image/webp') {
    throw new Error(
      `Thumbnail blob must have MIME type 'image/webp', but received '${thumbnailBlob.type}'.`
    );
  }
  if (thumbnailBlob.size > MAX_THUMBNAIL_FILE_SIZE_BYTES) {
    const sizeInMB = (thumbnailBlob.size / (1024 * 1024)).toFixed(1);
    throw new Error(`Thumbnail blob (${sizeInMB} MB) exceeds the maximum allowed limit of 10 MB.`);
  }

  // 4. Verify Supabase client configuration
  if (!isSupabaseConfigured) {
    throw new Error('Supabase client is not configured. Cannot perform Storage upload.');
  }

  // 5. Verify authenticated staff user session
  const { data: authData, error: authError } = await supabase.auth.getUser();
  if (authError || !authData?.user) {
    throw new Error(
      'Authentication required: A valid authenticated staff session is required to upload community gallery photos.'
    );
  }

  const userId = authData.user.id;
  const timestamp = Date.now();
  const uniqueId = generateUniqueId();
  const { ext, contentType: originalContentType } = resolveFileExtension(
    normalizedMime,
    originalFile.name
  );

  // Generate collision-resistant paths organized by user ID
  const imagePath = `${userId}/${timestamp}_${uniqueId}.${ext}`;
  const thumbnailPath = `${userId}/${timestamp}_${uniqueId}.webp`;

  // 6. Upload original image to `roa-gallery`
  const { error: originalUploadError } = await supabase.storage
    .from(GALLERY_ORIGINAL_BUCKET)
    .upload(imagePath, originalFile, {
      contentType: originalContentType,
      upsert: false,
    });

  if (originalUploadError) {
    throw new Error(`Failed to upload original photo to storage: ${originalUploadError.message}`);
  }

  // 7. Upload thumbnail to `roa-thumbnails`
  const { error: thumbnailUploadError } = await supabase.storage
    .from(GALLERY_THUMBNAIL_BUCKET)
    .upload(thumbnailPath, thumbnailBlob, {
      contentType: 'image/webp',
      upsert: false,
    });

  if (thumbnailUploadError) {
    // Attempt rollback of the original image to prevent orphaned storage objects
    let rollbackMessage = '';
    try {
      const { error: rollbackError } = await supabase.storage
        .from(GALLERY_ORIGINAL_BUCKET)
        .remove([imagePath]);

      if (rollbackError) {
        rollbackMessage = ` (Warning: Could not rollback original object at ${imagePath}: ${rollbackError.message})`;
      } else {
        rollbackMessage = ' (Original object was safely rolled back.)';
      }
    } catch (cleanupErr: any) {
      rollbackMessage = ` (Warning: Rollback error: ${cleanupErr?.message || cleanupErr})`;
    }

    throw new Error(
      `Failed to upload thumbnail to storage: ${thumbnailUploadError.message}.${rollbackMessage}`
    );
  }

  return {
    imagePath,
    thumbnailPath,
  };
}

/**
 * Removes uploaded gallery storage objects if database insertion or later processing fails.
 */
export async function deleteUploadedGalleryStorageObjects(
  imagePath?: string | null,
  thumbnailPath?: string | null
): Promise<StorageCleanupResult> {
  const errors: string[] = [];

  if (imagePath && isStoragePath(imagePath)) {
    try {
      const { error } = await supabase.storage
        .from(GALLERY_ORIGINAL_BUCKET)
        .remove([imagePath]);
      if (error) {
        errors.push(`roa-gallery cleanup error (${imagePath}): ${error.message}`);
      }
    } catch (err: any) {
      errors.push(`roa-gallery cleanup exception: ${err?.message || err}`);
    }
  }

  if (thumbnailPath && isStoragePath(thumbnailPath)) {
    try {
      const { error } = await supabase.storage
        .from(GALLERY_THUMBNAIL_BUCKET)
        .remove([thumbnailPath]);
      if (error) {
        errors.push(`roa-thumbnails cleanup error (${thumbnailPath}): ${error.message}`);
      }
    } catch (err: any) {
      errors.push(`roa-thumbnails cleanup exception: ${err?.message || err}`);
    }
  }

  return {
    ok: errors.length === 0,
    errors,
  };
}

// In-memory cache for temporary signed URLs to prevent redundant network requests
interface CachedSignedUrlEntry {
  url: string;
  expiresAt: number;
}

const signedUrlMemoryCache = new Map<string, CachedSignedUrlEntry>();

/**
 * Clears the in-memory signed URL cache.
 */
export function clearSignedUrlCache(): void {
  signedUrlMemoryCache.clear();
}

/**
 * Resolves a Storage object path into a temporary signed URL.
 *
 * Rules:
 * - Local paths starting with `/` are returned unchanged.
 * - External HTTP/HTTPS URLs are returned unchanged.
 * - Data and blob URLs are returned unchanged.
 * - Empty or missing paths return an empty string.
 * - Private storage paths request a temporary signed URL with the specified expiry (default 1 hr).
 * - Utilizes an in-memory session cache to avoid repeatedly generating signed URLs on every render.
 * - Automatically refreshes signed URLs when nearing expiration.
 * - Never returns a raw private Storage path when signed URL generation fails.
 * - Surfaces a clear error if Supabase is unconfigured or signing fails.
 * - Never persists the generated signed URL in localStorage or database.
 */
export async function getSignedGalleryUrl(
  path: string | null | undefined,
  type: 'original' | 'thumbnail' = 'original',
  expiresIn: number = DEFAULT_SIGNED_URL_EXPIRY_SECONDS
): Promise<string> {
  if (!path || typeof path !== 'string') {
    return '';
  }

  const trimmed = path.trim();
  if (trimmed === '') {
    return '';
  }

  // Preserve local paths (/...) and external URLs (http...) unchanged
  if (!isStoragePath(trimmed)) {
    // If it's a recognized non-storage path format, return directly
    if (trimmed.startsWith('/') || /^(https?:|data:|blob:)/i.test(trimmed)) {
      return trimmed;
    }
    // If it is neither a recognized local/external URL nor a valid storage path,
    // reject it rather than returning or attempting to sign an invalid path
    throw new Error(`Unrecognized image path format: '${trimmed}'.`);
  }

  // Check in-memory cache first (with 60-second safety buffer before expiry)
  const bucket = type === 'thumbnail' ? GALLERY_THUMBNAIL_BUCKET : GALLERY_ORIGINAL_BUCKET;
  const cacheKey = `${bucket}:${trimmed}`;
  const cached = signedUrlMemoryCache.get(cacheKey);
  if (cached && cached.expiresAt > Date.now() + 60_000) {
    return cached.url;
  }

  // Private storage path: verify Supabase is configured
  if (!isSupabaseConfigured) {
    throw new Error(
      `Cannot generate signed URL for private storage object '${trimmed}': Supabase client is not configured.`
    );
  }

  const { data, error } = await supabase.storage
    .from(bucket)
    .createSignedUrl(trimmed, expiresIn);

  if (error || !data?.signedUrl) {
    const errorDetails = error?.message || 'No signed URL was returned.';
    throw new Error(
      `Failed to generate signed URL for private storage object '${bucket}/${trimmed}': ${errorDetails}`
    );
  }

  // Store in in-memory session cache
  signedUrlMemoryCache.set(cacheKey, {
    url: data.signedUrl,
    expiresAt: Date.now() + expiresIn * 1000,
  });

  return data.signedUrl;
}

/**
 * Resolves both original and thumbnail signed URLs for a gallery item.
 * If the thumbnail path is missing, falls back gracefully to the original image URL.
 */
export async function resolveGalleryItemUrls(
  item: { imageUrl: string; thumbnailUrl?: string | null },
  expiresIn: number = DEFAULT_SIGNED_URL_EXPIRY_SECONDS
): Promise<{ imageUrl: string; thumbnailUrl: string }> {
  if (!item.imageUrl) {
    return { imageUrl: '', thumbnailUrl: '' };
  }

  const originalPromise = getSignedGalleryUrl(item.imageUrl, 'original', expiresIn);
  const thumbnailPromise = item.thumbnailUrl
    ? getSignedGalleryUrl(item.thumbnailUrl, 'thumbnail', expiresIn)
    : originalPromise;

  const [imageUrl, thumbnailUrl] = await Promise.all([originalPromise, thumbnailPromise]);
  return {
    imageUrl,
    thumbnailUrl: thumbnailUrl || imageUrl,
  };
}
